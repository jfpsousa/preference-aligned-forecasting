"""
Stage 6 -- build every table and figure dataset from the raw run files.

Reads only <output>/runs/**/{main,ablation,sweep,beta}.json, which the previous
stages wrote; nothing is hard-coded. Writes to <output>/tables/:

    table2_synthetic.{csv,tex}       Table 2 and Figure 2 (both panels)
    table2_per_domain.csv            Table 2 broken down by domain
    table3_real.{csv,tex}            Table 3
    table4_cost_ratio.{csv,tex}      Table 4
    figure3_gamma.csv                Figure 3, left
    figure3_sample_efficiency.csv    Figure 3, right
    ablation_principles.csv          Section 7.4, constitutional principles
    ablation_reference_policy.csv    Section 7.4, reference policy
    ablation_beta.csv                Section 7.4, inverse temperature beta
    beta_selection.csv               Section 7.1, beta chosen on the validation set
    significance.csv                 Appendix C, paired t-tests across seeds
    headline_numbers.csv             percentages quoted in the abstract and text
    tableS1_action_set_size.csv      sensitivity of Eqs. (15)-(16) to |A|
    SUMMARY.md                       everything above, human-readable
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from tpo.config import load_config  # noqa: E402

LABELS = {"naive": "Naive", "mse": "MSE Baseline", "patchtst": "PatchTST",
          "informer": "Informer", "asymmetric": "Asymmetric Loss",
          "tdpo": "Temporal-DPO", "oracle": "Oracle"}
DS_LABELS = {"m5": "M5 (Retail)", "uci_energy": "UCI Energy", "yahoo_etf": "Yahoo ETFs",
             "synthetic_retail": "Synthetic retail", "synthetic_energy": "Synthetic energy",
             "synthetic_finance": "Synthetic finance"}


def se(x):
    x = np.asarray(x, dtype=float)
    return float(x.std(ddof=1) / np.sqrt(len(x))) if len(x) > 1 else float("nan")


def load(out, name, seed, job):
    p = out / "runs" / name / f"seed{seed}" / f"{job}.json"
    if not p.exists():
        raise FileNotFoundError(f"missing {p}; run the '{job}' stage first")
    return json.loads(p.read_text())


def norm_cost(methods, m):
    return 100.0 * methods[m]["cost"] / methods["mse"]["cost"]


def paired(a, b):
    a, b = np.asarray(a), np.asarray(b)
    if len(a) < 2 or np.allclose(a - b, (a - b)[0]):
        return float("nan"), float("nan")
    t, p = stats.ttest_rel(a, b)
    return float(t), float(p)


def to_tex(df, caption, label, path):
    cols = "l" * (df.shape[1] - 3) + "ccc" if df.shape[1] >= 3 else "l" * df.shape[1]
    body = df.to_latex(index=False, escape=True, float_format="%.3f", column_format=cols)
    path.write_text(f"% generated by scripts/make_tables.py\n\\begin{{table}}[t]\n"
                    f"\\centering\n\\caption{{{caption}}}\n\\label{{{label}}}\n"
                    f"{body}\\end{{table}}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--output", required=True)
    args = ap.parse_args()
    cfg = load_config(args.config)
    out = Path(args.output)
    tdir = out / "tables"
    tdir.mkdir(parents=True, exist_ok=True)
    seeds, exp = cfg["seeds"], cfg["experiments"]
    md = [f"# Reproduced results\n\nSeeds: {seeds}. Mean over seeds; "
          f"standard errors (SE) across seeds. Decision accuracy (Eq. 15) and cost "
          f"(Eq. 16) use |A| = {cfg['evaluation']['n_actions']} actions. Cost is "
          f"normalised per domain and seed so that the MSE baseline = 100.\n"]
    sig_rows, head = [], []

    # ---------------- Table 2 (synthetic, averaged over domains) -------------
    t2m = exp["table2_methods"]
    per_seed = {m: {"mse": [], "acc": [], "cost": []} for m in t2m}
    dom_rows = []
    for s in seeds:
        acc = {m: [] for m in t2m}
        mse = {m: [] for m in t2m}
        cst = {m: [] for m in t2m}
        for name in exp["table2_datasets"]:
            r = load(out, name, s, "main")["methods"]
            for m in t2m:
                acc[m].append(r[m]["decision_accuracy"])
                mse[m].append(r[m]["mse"])
                cst[m].append(norm_cost(r, m))
                dom_rows.append({"dataset": name, "seed": s, "method": m,
                                 "mse": r[m]["mse"], "decision_accuracy":
                                 r[m]["decision_accuracy"], "cost_norm": norm_cost(r, m),
                                 "cost_raw": r[m]["cost"]})
        for m in t2m:
            per_seed[m]["mse"].append(np.mean(mse[m]))
            per_seed[m]["acc"].append(np.mean(acc[m]))
            per_seed[m]["cost"].append(np.mean(cst[m]))
    t2 = pd.DataFrame([{"Method": LABELS[m],
                        "MSE": np.mean(per_seed[m]["mse"]),
                        "Decision Acc.": np.mean(per_seed[m]["acc"]),
                        "Cost": np.mean(per_seed[m]["cost"]),
                        "SE MSE": se(per_seed[m]["mse"]),
                        "SE Acc.": se(per_seed[m]["acc"]),
                        "SE Cost": se(per_seed[m]["cost"])} for m in t2m])
    t2.to_csv(tdir / "table2_synthetic.csv", index=False)
    to_tex(t2[["Method", "MSE", "Decision Acc.", "Cost"]],
           "Performance comparison across all domains (averaged). Cost is normalized "
           "(MSE Baseline = 100).", "tab:main_results", tdir / "table2_synthetic.tex")
    dd = pd.DataFrame(dom_rows)
    dd.groupby(["dataset", "method"])[["mse", "decision_accuracy", "cost_norm", "cost_raw"]] \
        .mean().reset_index().to_csv(tdir / "table2_per_domain.csv", index=False)
    md += ["## Table 2 / Figure 2 — synthetic domains, averaged\n",
           t2.to_markdown(index=False, floatfmt=".3f"), ""]
    for m in t2m:
        if m == "tdpo":
            continue
        for metric in ("acc", "cost"):
            t, p = paired(per_seed["tdpo"][metric], per_seed[m][metric])
            sig_rows.append({"table": "2", "dataset": "synthetic (avg)",
                             "comparison": f"tdpo vs {m}", "metric": metric,
                             "mean_diff": float(np.mean(per_seed["tdpo"][metric])
                                                - np.mean(per_seed[m][metric])),
                             "t": t, "p": p, "n_seeds": len(seeds)})
    a = {m: np.mean(per_seed[m]["acc"]) for m in t2m}
    c = {m: np.mean(per_seed[m]["cost"]) for m in t2m}
    head += [
        ("T-DPO decision accuracy (Table 2)", a["tdpo"]),
        ("Decision-accuracy improvement vs MSE, relative %", 100 * (a["tdpo"] / a["mse"] - 1)),
        ("Decision-accuracy improvement vs Asymmetric, relative %",
         100 * (a["tdpo"] / a["asymmetric"] - 1)),
        ("Cost reduction vs MSE %", 100 - c["tdpo"]),
        ("Cost reduction vs Asymmetric %", 100 * (1 - c["tdpo"] / c["asymmetric"])),
        ("Oracle decision accuracy (Table 2)", a["oracle"]),
    ]

    # ---------------- Table 3 (real data) ------------------------------------
    t3m = exp["table3_methods"]
    rows, rel_imp = [], []
    for name in exp["table3_datasets"]:
        vals = {m: {"mse": [], "acc": [], "cost": []} for m in t3m}
        for s in seeds:
            r = load(out, name, s, "main")["methods"]
            for m in t3m:
                vals[m]["mse"].append(r[m]["mse"])
                vals[m]["acc"].append(r[m]["decision_accuracy"])
                vals[m]["cost"].append(norm_cost(r, m))
        for m in t3m:
            rows.append({"Dataset": DS_LABELS[name], "Method": LABELS[m],
                         "MSE": np.mean(vals[m]["mse"]), "Acc.": np.mean(vals[m]["acc"]),
                         "Cost": np.mean(vals[m]["cost"]), "SE MSE": se(vals[m]["mse"]),
                         "SE Acc.": se(vals[m]["acc"]), "SE Cost": se(vals[m]["cost"])})
            if m != "tdpo":
                for metric in ("acc", "cost"):
                    t, p = paired(vals["tdpo"][metric], vals[m][metric])
                    sig_rows.append({"table": "3", "dataset": name,
                                     "comparison": f"tdpo vs {m}", "metric": metric,
                                     "mean_diff": float(np.mean(vals["tdpo"][metric])
                                                        - np.mean(vals[m][metric])),
                                     "t": t, "p": p, "n_seeds": len(seeds)})
        rel_imp.append(100 * (np.mean(vals["tdpo"]["acc"]) / np.mean(vals["mse"]["acc"]) - 1))
    t3 = pd.DataFrame(rows)
    t3.to_csv(tdir / "table3_real.csv", index=False)
    to_tex(t3[["Dataset", "Method", "MSE", "Acc.", "Cost"]],
           "Performance on real-world benchmarks. Cost is normalized per domain (MSE = 100).",
           "tab:real_results", tdir / "table3_real.tex")
    md += ["## Table 3 — real-world benchmarks\n", t3.to_markdown(index=False, floatfmt=".3f"), ""]
    head.append(("Average decision-accuracy improvement vs MSE on real data, relative %",
                 float(np.mean(rel_imp))))

    # ---------------- Table 4 (cost-ratio sweep) -----------------------------
    rows = []
    for alpha in exp["cost_ratio_grid"]:
        acc_, rm, ra = [], [], []
        for s in seeds:
            r = load(out, exp["cost_ratio_dataset"], s, "sweep")["alpha"][str(alpha)]
            acc_.append(100 * r["tdpo"]["decision_accuracy"])
            rm.append(100 * (1 - r["tdpo"]["cost"] / r["mse"]["cost"]))
            ra.append(100 * (1 - r["tdpo"]["cost"] / r["asymmetric"]["cost"]))
        rows.append({"Ratio alpha": alpha, "Decision Acc. (%)": np.mean(acc_),
                     "Cost red. vs MSE (%)": np.mean(rm),
                     "Cost red. vs Asym. (%)": np.mean(ra),
                     "SE Acc.": se(acc_), "SE red. MSE": se(rm), "SE red. Asym.": se(ra)})
    t4 = pd.DataFrame(rows)
    t4.to_csv(tdir / "table4_cost_ratio.csv", index=False)
    to_tex(t4[["Ratio alpha", "Decision Acc. (%)", "Cost red. vs MSE (%)",
               "Cost red. vs Asym. (%)"]],
           "Sensitivity of retail (M5) results to the stockout-to-holding cost ratio.",
           "tab:sensitivity", tdir / "table4_cost_ratio.tex")
    md += ["## Table 4 — cost-ratio sensitivity (M5)\n",
           t4.to_markdown(index=False, floatfmt=".2f"), ""]

    # ---------------- Ablations (Figure 3, Section 7.4) ----------------------
    abl = {(n, s): load(out, n, s, "ablation")
           for n in exp["ablation_datasets"] for s in seeds}
    mains = {(n, s): load(out, n, s, "main")["methods"]
             for n in exp["ablation_datasets"] for s in seeds}

    def avg_over_domains(getter):
        """mean over seeds of (mean over ablation domains); returns (mean, se)."""
        per = [np.mean([getter(abl[(n, s)], mains[(n, s)]) for n in exp["ablation_datasets"]])
               for s in seeds]
        return float(np.mean(per)), se(per)

    rows = []
    for g in exp["gamma_grid"]:
        mu, e = avg_over_domains(lambda A, M: A["gamma"][str(g)]["decision_accuracy"])
        cm, ce = avg_over_domains(
            lambda A, M: 100 * A["gamma"][str(g)]["cost"] / M["mse"]["cost"])
        rows.append({"gamma": g, "Decision Acc. (%)": 100 * mu, "SE (pp)": 100 * e,
                     "Cost (MSE=100)": cm, "SE Cost": ce})
    fg = pd.DataFrame(rows)
    fg.to_csv(tdir / "figure3_gamma.csv", index=False)
    md += ["## Figure 3 (left) — temporal discount γ\n",
           fg.to_markdown(index=False, floatfmt=".2f"), ""]
    peak = fg["Decision Acc. (%)"].max()
    g1 = fg.loc[np.isclose(fg["gamma"], 1.0), "Decision Acc. (%)"]
    g95 = fg.loc[np.isclose(fg["gamma"], cfg["tdpo"]["gamma"]), "Decision Acc. (%)"]
    if len(g1) and len(g95):
        head.append(("Decision accuracy at gamma=1 minus gamma=0.95 (pp)",
                     float(g1.iloc[0] - g95.iloc[0])))
    head.append(("Best gamma in grid", float(fg.loc[fg["Decision Acc. (%)"].idxmax(), "gamma"])))
    head.append(("Peak decision accuracy over gamma grid (%)", float(peak)))

    rows = []
    for n in exp["pair_grid"]:
        row = {"n": n}
        for meth in ("tdpo", "asymmetric"):
            mu, e = avg_over_domains(
                lambda A, M: A["sample_efficiency"][meth][str(n)]["decision_accuracy"])
            row[f"{LABELS[meth]} Acc. (%)"] = 100 * mu
            row[f"{LABELS[meth]} SE (pp)"] = 100 * e
        rows.append(row)
    fs = pd.DataFrame(rows)
    fs.to_csv(tdir / "figure3_sample_efficiency.csv", index=False)
    md += ["## Figure 3 (right) — sample efficiency\n",
           fs.to_markdown(index=False, floatfmt=".2f"), ""]

    rows = []
    for v in ["all", "without_P1", "without_P2", "without_P3", "without_P4", "none"]:
        mu, e = avg_over_domains(lambda A, M: A["principles"][v]["decision_accuracy"])
        cm, ce = avg_over_domains(
            lambda A, M: 100 * A["principles"][v]["cost"] / M["mse"]["cost"])
        rows.append({"variant": v, "Decision Acc. (%)": 100 * mu, "SE (pp)": 100 * e,
                     "Cost (MSE=100)": cm, "SE Cost": ce})
    fp = pd.DataFrame(rows)
    fp.to_csv(tdir / "ablation_principles.csv", index=False)
    md += ["## Section 7.4 — constitutional principles\n",
           "`none` = candidates ranked by squared error only (no principles).\n",
           fp.to_markdown(index=False, floatfmt=".2f"), ""]

    rows = []
    for v in ["pretrained", "random_init"]:
        mu, e = avg_over_domains(lambda A, M: A["reference_policy"][v]["decision_accuracy"])
        cm, _ = avg_over_domains(
            lambda A, M: 100 * A["reference_policy"][v]["cost"] / M["mse"]["cost"])
        fl, _ = avg_over_domains(
            lambda A, M: A["reference_policy"][v]["training_curve"]["loss"][-1])
        fa, _ = avg_over_domains(
            lambda A, M: A["reference_policy"][v]["training_curve"]["preference_accuracy"][-1])
        mse_, _ = avg_over_domains(lambda A, M: A["reference_policy"][v]["mse"])
        rows.append({"reference": v, "Decision Acc. (%)": 100 * mu, "SE (pp)": 100 * e,
                     "Cost (MSE=100)": cm, "MSE": mse_, "final DPO loss": fl,
                     "final preference acc.": fa})
    fr = pd.DataFrame(rows)
    fr.to_csv(tdir / "ablation_reference_policy.csv", index=False)
    md += ["## Section 7.4 — reference policy\n", fr.to_markdown(index=False, floatfmt=".3f"), ""]

    # ---------------- beta (Sec. 7.1 selection, Sec. 7.4 ablation) ----------
    rows, sel_rows = [], []
    for name in exp["beta_datasets"]:
        B = [load(out, name, s, "beta") for s in seeds]
        for b in exp["beta_grid"]:
            r = {"Dataset": DS_LABELS[name], "beta": b,
                 "in ablation grid": b in exp["beta_ablation_grid"],
                 "in selection grid": b in exp["beta_selection_grid"]}
            for split in ("val", "test"):
                acc = [100 * x["beta"][str(b)][split]["decision_accuracy"] for x in B]
                cst = [100 * x["beta"][str(b)][split]["cost"] / x["mse"][split]["cost"]
                       for x in B]
                r[f"{split} Acc. (%)"] = np.mean(acc)
                r[f"{split} SE (pp)"] = se(acc)
                r[f"{split} Cost (MSE=100)"] = np.mean(cst)
            rows.append(r)
        picks = [x["selected_beta"] for x in B]
        for s, x in zip(seeds, B):
            sel_rows.append({"Dataset": DS_LABELS[name], "seed": s,
                             "selected beta": x["selected_beta"],
                             "criterion (validation)": x["selection_metric"],
                             "configured beta": cfg["tdpo"]["beta"]})
        head.append((f"Seeds where validation selects the configured beta "
                     f"({cfg['tdpo']['beta']}), {name}",
                     float(np.sum(np.isclose(picks, cfg["tdpo"]["beta"])))))
    fb = pd.DataFrame(rows)
    fb.to_csv(tdir / "ablation_beta.csv", index=False)
    fsel = pd.DataFrame(sel_rows)
    fsel.to_csv(tdir / "beta_selection.csv", index=False)
    md += ["## Section 7.4 — inverse temperature β (test windows; validation shown "
           "for selection)\n", fb.to_markdown(index=False, floatfmt=".2f"), "",
           "## Section 7.1 — β selected on the validation set, per seed\n",
           fsel.to_markdown(index=False), ""]

    # ---------------- significance, headline numbers, |A| sensitivity --------
    sig = pd.DataFrame(sig_rows)
    sig.to_csv(tdir / "significance.csv", index=False)
    md += ["## Appendix C — paired t-tests across seeds (T-DPO minus baseline)\n",
           sig.to_markdown(index=False, floatfmt=".4g"), ""]
    hd = pd.DataFrame(head, columns=["quantity", "value"])
    hd.to_csv(tdir / "headline_numbers.csv", index=False)
    md += ["## Numbers quoted in the text\n", hd.to_markdown(index=False, floatfmt=".2f"), ""]

    rows = []
    for name in list(dict.fromkeys(exp["table2_datasets"] + exp["table3_datasets"])):
        for s in seeds:
            r = load(out, name, s, "main")["methods"]
            for m, res in r.items():
                for n, v in res["by_n_actions"].items():
                    rows.append({"dataset": name, "seed": s, "method": m, "n_actions": int(n),
                                 "decision_accuracy": v["decision_accuracy"],
                                 "cost_norm": 100 * v["cost"] / r["mse"]["by_n_actions"][n]["cost"]})
    sa = (pd.DataFrame(rows).groupby(["dataset", "method", "n_actions"])
          [["decision_accuracy", "cost_norm"]].mean().reset_index())
    sa.to_csv(tdir / "tableS1_action_set_size.csv", index=False)
    piv = sa[sa.method.isin(["mse", "tdpo"])].pivot_table(
        index=["dataset", "n_actions"], columns="method",
        values=["decision_accuracy", "cost_norm"]).round(3)
    md += ["## Table S1 — sensitivity to the action-set size |A|\n",
           piv.to_markdown(), ""]

    (tdir / "SUMMARY.md").write_text("\n".join(md))
    print("\n".join(md))
    print(f"\nTables written to {tdir}")


if __name__ == "__main__":
    main()
